// Gently meandering points along a river (degrees).
export function meander(pts, k) {
  const out = [];
  for (let s = 0; s < pts.length - 1; s++) {
    const [a0, b0] = pts[s], [a1, b1] = pts[s + 1];
    const len = Math.hypot(a1 - a0, b1 - b0), n = Math.max(1, Math.ceil(len / 0.2));
    const nx = -(b1 - b0) / (len || 1), ny = (a1 - a0) / (len || 1);
    for (let i = 0; i < n; i++) {
      const t = i / n, d = s + t;
      const amp = 0.12 * Math.sin(d * 2.7 + k) + 0.06 * Math.sin(d * 7.3 + k * 2);
      out.push([a0 + (a1 - a0) * t + nx * amp, b0 + (b1 - b0) * t + ny * amp]);
    }
  }
  out.push(pts[pts.length - 1]);
  return out;
}
